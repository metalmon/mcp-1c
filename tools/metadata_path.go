package tools

import (
	"fmt"
	"net/url"
	"strings"
)

// metadataPathPart проверяет и экранирует кусок адреса точки 1С, собираемый из
// того, что прислал агент (тип и имя объекта метаданных).
//
// Зачем: адрес склеивался как fmt.Sprintf("/object/%s/%s", …) и уходил в
// клиент как есть, поэтому тип `../event-log` уводил ЧИТАЮЩИЙ запрос на другую
// точку той же публикации — к тем GET-ам, которых набор инструментов нарочно
// не даёт (находка ревью 3.11.2026). Файловая половина того же инструмента
// (dump.FindFormFiles) так защищена с самого начала; эта функция — та же мерка
// для сетевой половины, одним местом на оба инструмента.
//
// Правило — запрещённые символы, а не список допустимых имён: виды метаданных
// описаны в самих инструментах словами «Document, Catalog, DataProcessor,
// Report и т.д.», а имена объектов бывают русскими, и закрытый список урезал бы
// работающее. Запрещаем ровно то, чем ломается путь: разделители, `..`, `%`
// (им `%2f` пролезает мимо проверки на `/`), `?` и `#`.
func metadataPathPart(what, v string) (string, error) {
	if strings.ContainsAny(v, `/\?#%`) || strings.Contains(v, "..") {
		return "", fmt.Errorf("invalid %s %q: contains path traversal characters", what, v)
	}
	return url.PathEscape(v), nil
}
