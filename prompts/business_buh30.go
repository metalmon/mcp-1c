func handleBuh30RevenueLeakageWatch(_ context.Context, _ *mcp.GetPromptRequest) (*mcp.GetPromptResult, error) {
	return promptResult(
		"Контроль утечки выручки Бухгалтерия 3.0",
		`Сделай многошаговый мониторинг потенциальной утечки выручки по всей базе Бухгалтерия 3.0 без входных параметров.

Шаги:
1. Вызови read_sales_invoices с {"limit":500} и получи выставленные счета.
2. Вызови read_sales_documents с {"limit":500} и получи реализации.
3. Построй базовый срез:
   - общий объем выставленной выручки (сумма счетов);
   - общий объем реализованной выручки (сумма реализаций);
   - абсолютный и процентный разрыв.
4. Найди точки утечки:
   - счета без реализаций;
   - реализации без invoice_ref;
   - счета/реализации с аномальным расхождением сумм.
5. Сегментируй риск:
   - топ-10 документов с максимальной потенциальной потерей;
   - топ-5 контрагентов, где сосредоточен основной риск.
6. Дай практический план реагирования:
   - быстрые действия на 48 часов;
   - контрольные меры на 30 дней для снижения повторения.

Требования к ответу:
- Используй строго 5 разделов:
  1) Объем и разрыв выручки
  2) Каналы утечки
  3) Топ риск-документов
  4) Топ риск-контрагентов
  5) План реагирования (48 часов / 30 дней)
- Если данных недостаточно, это нужно явно отметить и продолжить анализ на доступном массиве.
- Не выдумывай недоступные поля и связи; опирайся только на результаты инструментов.`,
	)
}
