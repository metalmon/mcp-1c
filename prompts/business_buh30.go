func handleBuh30CFOCashflowRiskSnapshot(_ context.Context, _ *mcp.GetPromptRequest) (*mcp.GetPromptResult, error) {
	return promptResult(
		"CFO-срез рисков денежного потока Бухгалтерия 3.0",
		`Подготовь управленческий риск-срез для финансового директора по всей базе Бухгалтерия 3.0 без входных параметров.

Шаги:
1. Вызови read_sales_invoices с {"limit":500} и получи данные по выставленным счетам.
2. Вызови read_sales_documents с {"limit":500} и получи данные по реализациям.
3. Построй CFO KPI:
   - сумма и количество выставленных счетов;
   - сумма и количество реализаций;
   - денежный разрыв (выставлено минус реализовано) в абсолюте и процентах.
4. Выяви ключевые риски:
   - зависшие счета (есть счет, нет реализации);
   - реализации без связи со счетом (invoice_ref пустой);
   - наибольшие расхождения сумм между связанными документами.
5. Сконцентрируй риски:
   - выдели топ-10 контрагентов/документов с максимальным потенциальным влиянием на денежный поток.
6. Сформируй действия на 7 дней:
   - какие документы и контрагентов разбирать первыми;
   - какие меры снизят кассовый разрыв быстрее всего.

Требования к ответу:
- Используй строго 5 разделов:
  1) Резюме для финдиректора (1-3 вывода)
  2) KPI для финдиректора
  3) Риски и потери выручки
  4) Топ-10 контрагентов/документов по риску
  5) Решения на ближайшие 7 дней
- Если данных недостаточно, явно это укажи и выдай предварительные выводы на доступном объеме.
- Не придумывай отсутствующие поля и связи; опирайся только на результаты инструментов.`,
	)
}

